def _default() -> dict:
    return {
        "status": "answered",
        "answer": "[Пример обычного ответа] Краткий ответ на вопрос по найденному положению, "
                  "со ссылкой на пункт или статью (п. ... договора; ст. ... закона). "
                  "До 150 слов.",
        "sources": _contract_sample(),
    }


def mock_answer(question: str, history: list[dict] | None = None) -> dict:
    """history принимается ради совпадения сигнатуры с assistant.answer(); моком не используется."""
    q = question.lower()
    for _name, triggers, build in SCENARIOS:
        if any(t in q for t in triggers):
            return build()
    return _default()